import { COMPATIBILITY } from "./compatibility";
import { TYPE_INFO } from "./type-info";

export type RelationshipTone = "synergy" | "growth" | "friction" | "collapse";

export interface TimelineEntry {
  day: string;
  title: string;
  event: string;
  tone: RelationshipTone;
}

function getArchetype(a: string, b: string): "dual" | "synergy" | "neutral" | "friction" | "clash" {
  if (a === b) return "dual";
  const compat = COMPATIBILITY[a as keyof typeof COMPATIBILITY];
  if (compat?.bestPartner.type === b) return "synergy";
  if (compat?.hardestMatch.type === b) return "clash";

  // Count letter matches
  const matches = [...a].filter((c, i) => c === b[i]).length;
  if (matches >= 3) return "neutral";
  return "friction";
}

function typeLabel(t: string): string {
  return `${t}（${TYPE_INFO[t]?.name ?? t}）`;
}

export function generateRelationshipTimeline(
  typeA: string,
  typeB: string
): TimelineEntry[] {
  const arch = getArchetype(typeA, typeB);
  const a = typeLabel(typeA);
  const b = typeLabel(typeB);

  // Dimension analysis
  const sameEI = typeA[0] === typeB[0];
  const sameSN = typeA[1] === typeB[1];
  const sameTF = typeA[2] === typeB[2];
  const sameJP = typeA[3] === typeB[3];

  const eiNote = sameEI
    ? `二人とも${typeA[0] === "E" ? "外向" : "内向"}型。バッテリーの充電スタイルが似ていて、「人と会って充電する」か「一人になって充電する」のタイミングが完璧に合う。`
    : `片方は人と会って充電するタイプ、もう片方は一人で充電するタイプ。「週末は外に行きたい！」vs「家で映画を見たい」の差が少しずつ積み重なる。`;

  const snNote = sameSN
    ? `話の「解像度」が同じ。「あの店のランチ美味しかった！」みたいなリアルな話か、「人生の意味って…」みたいな深い話か、どっちかに綺麗に揃ってる。`
    : `一方は「で、現実はどうなの？」とリアルな結果を求めるのに、もう一方は「そもそも人生の概念は…」と壮大な話に飛ぶ。この会話のズレが少しもどかしい。`;

  const tfNote = sameTF
    ? `「正論で解決するか」か「共感して寄り添うか」か、悩んだ時の対応が揃ってる。喧嘩しても「何が嫌だったか」の基準が同じだから仲直りしやすい。`
    : `片方は「正論とアドバイス」で返し、もう片方は「感情と共感」を求める。同じことで悩んでるのに、まったく違う部分ですれ違う。`;

  const jpNote = sameJP
    ? `予定の「決め方」が似てる。ガッチリ予定立てるか、その場のノリで動くかが同じだから、遊びの約束をするのもスムーズ。`
    : `一方は「旅行の計画は前もって立てたい」派、もう一方は「とりあえず駅集合でよくない？」派。遊ぶ予定を立てるだけで小さなイライラが起こりやすい。`;

  switch (arch) {
    case "dual":
      return [
        {
          day: "Day 1",
          title: "「なんかこの人、すごく気が合う」",
          event: `${a}と${b}、全く同じタイプの二人。考え方からLINEのテンポまで自分とそっくりで、「なんか一緒にいてラクだな」という感覚が生まれる。でもそれ、少し不思議でもある。自分が隠してきた本音とか裏の顔まで、全部見透かされてる気がするから。`,
          tone: "synergy",
        },
        {
          day: "Day 30",
          title: "「あ、自分の直したいところ相手もやってる」",
          event: `1ヶ月後、相手の気になる部分が見えてくる。でもそれ、自分自身のダメな部分と全く同じ。自分が一番気にしている「抜けている部分」を、相手が目の前でそのままやる。「これ、自分もやってるやつだ…」と気づき、少し苦い自問自答が始まる。`,
          tone: "growth",
        },
        {
          day: "Day 100",
          title: "「いや、私の方が正しい」の平行線",
          event: `同じ思考回路で同じ課題に向かう二人。うまくいく時は最高の相棒だけど、意見がぶつかると誰も引かない。${tfNote}「自分の方が絶対に正しい」という根拠が同じだから、平行線になりやすい。この時期にどう歩み寄るかで、この関係の未来が決まる。`,
          tone: "friction",
        },
        {
          day: "Day 365",
          title: "最高の理解者か、そっと離れるか",
          event: `1年後、二人は互いのダメなところを知り尽くした上で、それでも一緒にいるパートナーになるか、それとも「もう同族嫌悪で無理」と穏やかに縁を切るか。どちらに転んでも、得たものは大きい。相手は、あなたが一番見たくなかった「自分自身」を正直に映し出してくれた鏡だから。`,
          tone: "growth",
        },
      ];

    case "synergy":
      return [
        {
          day: "Day 1",
          title: "「全然タイプ違うのに、なんか落ち着く」",
          event: `${a}と${b}の出会。${eiNote}性格は全然違うのに、一緒にいると「あ、なんか波長合うな」という不思議な感覚がある。「この人といると、いつも無理してたことが自然にできる」という、パズルのピースがハマったような体験が始まる。`,
          tone: "synergy",
        },
        {
          day: "Day 30",
          title: "「得意なことが逆」で、バランスが良い",
          event: `${snNote}最初はこの「違い」が新鮮で楽しい。一方が苦手なことを、もう一方がさらっと片付けてくれる。でも気をつけて。いつも「サポートしている」と感じる方が、少しずつストレスを溜める時期でもある。「私ばかり頑張っている…」という不満は、ちゃんと小出しにしないと後で爆発するよ。`,
          tone: "growth",
        },
        {
          day: "Day 100",
          title: "「違い」が最大の強みになった",
          event: `${tfNote}3ヶ月後、二人の「違い」はもうストレスじゃない。むしろ完璧な凸凹コンビとして機能し始めている。自分一人じゃ絶対に乗り越えられないピンチを、相手が全く違う視点から救ってくれる。「この人なしで今までどうしてきたんだろう」と思い始めるのは、このくらいの時期。`,
          tone: "synergy",
        },
        {
          day: "Day 365",
          title: "言葉にしなくても分かる、信頼関係",
          event: `1年後、二人はお互いのことを「自分にはないものを持ってる最強のパートナー」としてリスペクトできてる。${jpNote}もちろん意見がぶつかることもある。でもその衝突すら、二人の絆を深くする要素になっている。相手の性格を「変えよう」とせず、「そういう人なんだ」と受け入れながら一緒にいられる。それがこのペアの一番の強み。`,
          tone: "synergy",
        },
      ];

    case "clash":
      return [
        {
          day: "Day 1",
          title: "「なんか、ノリ合わないかも」",
          event: `${a}と${b}、最初の出会いから「なんか話が噛み合わないな」という感覚がある。${eiNote}LINEのテンポ、盛り上がるポイント、何に怒るか——根本的な価値観が合わない。どっちが悪いわけじゃない。ただ、互いの「普通」が全く違うだけ。それが分かるのは、もう少し時間が経ってから。`,
          tone: "friction",
        },
        {
          day: "Day 30",
          title: "「なんでそうなるの？」のすれ違い",
          event: `${snNote}付き合いが長くなると、お互いの本音が見えてきて本格的にすれ違い始める。${tfNote}二人が同時に「この人、本当に理解できない」とモヤモヤする瞬間がある。でも実は、どちらも間違ったことはしていない。「何を『正しい』と思うか」が、根本的に違うだけ。それが一番もどかしい。`,
          tone: "friction",
        },
        {
          day: "Day 100",
          title: "意見をぶつけるより、距離を置く選択",
          event: `${jpNote}3ヶ月後、表向きの衝突は減る。でも理解し合えたわけじゃない。「この話はしても無駄」「これ以上は踏み込まない」という心の壁が増えていく。二人とも、あのしんどい衝突より、今の少し冷めた距離感の方がマシだと気づいている。`,
          tone: "collapse",
        },
        {
          day: "Day 365",
          title: "それでも、なぜか縁が切れない関係",
          event: `1年後、この二人がまだ一緒にいるとしたら、互いに期待値をずいぶん下げた結果だ。完全に分かり合えることはないかもしれない。でも、お互いにぶつかり合いながらも一緒にいる二人は、心の中で何を持ってるんだろう。「違いすぎるからこそ惹かれる」という、理屈じゃないものがあるのかもしれない。`,
          tone: "friction",
        },
      ];

    case "friction":
      return [
        {
          day: "Day 1",
          title: "「なんか、少し住む世界が違うな」",
          event: `${a}と${b}の出会い。大喧嘩するわけじゃないけど、すごく盛り上がるわけでもない。でも一緒にいると、相手の言葉遣いとか考え方に、小さな「違和感」が積み重なっていく。「嫌い」じゃなくて、「別世界の人」という感覚。${eiNote}`,
          tone: "growth",
        },
        {
          day: "Day 30",
          title: "「この人、本当に不思議だな」",
          event: `${snNote}1ヶ月後、相手が自分とは全く違う「ルール」で生きてるのが分かってくる。${tfNote}どっちが正しいかとかじゃない。物事の優先順位が全然違う。これを「自分にはない発想で面白い！」と思えるか、「本当に話が通じない」と思うかで、この先の関係が変わってくる。`,
          tone: "friction",
        },
        {
          day: "Day 100",
          title: "「理解し合う」か、「距離を置く」か",
          event: `${jpNote}3ヶ月後、この関係は分岐点に立つ。「この人はこういう考え方なんだな」と受け入れて、違いを楽しめるなら、二人とも人間として大きく成長できる。でも「やっぱり価値観合わないな」と心を閉ざしてしまえば、最低限の挨拶だけの関係になっていく。どちらに進むかは、二人の意志次第。`,
          tone: "friction",
        },
        {
          day: "Day 365",
          title: "「全部は分からないけど、一緒にいる」",
          event: `1年後、この二人はお互いのことを100%は理解できていない。でも、分からないまま一緒にいることを選んでいる。完全に価値観が一致しなくても、「それでも一緒にいたい」と思える関係は、意外と尊い。その不完全さを丸ごと許容して付き合っていること自体が、二人の絆の強さの証明だよ。`,
          tone: "growth",
        },
      ];

    default: // neutral
      return [
        {
          day: "Day 1",
          title: "「普通にいい人だな」、それだけ",
          event: `${a}と${b}の出会い。運命的なビビッと感もないし、最悪な第一印象でもない。でも一緒にいると、自然にテンポが合う。似てるところと違うところがちょうど良く混ざってて、気を使わない。${eiNote}この「普通に一緒にいてラク」という感覚こそが、後々最大の強みになる。`,
          tone: "growth",
        },
        {
          day: "Day 30",
          title: "「お、こういう考え方するんだ」",
          event: `${snNote}1ヶ月後、相手の「自分とは違う部分」が見えてくる。${tfNote}大きな衝突になることはなくて、「へー、そういう見方もあるんだね」と素直に感心することの方が多い。自然に相手のペースに合わせられるようになっていて、気づいたらお互いへの信頼が積み上がっている。`,
          tone: "growth",
        },
        {
          day: "Day 100",
          title: "大きな衝突もないけど、安定してる",
          event: `${jpNote}3ヶ月後、二人の関係は「安定期」に入っている。劇的なサプライズもないし、激しい愛憎劇もない。でもそれって、すごいことだと思う。「なんとなく今日も一緒にいたいな」と思える相手は、実はとても貴重。この「穏やかな平和」を過小評価しちゃダメだよ。`,
          tone: "synergy",
        },
        {
          day: "Day 365",
          title: "「いつも隣にいるのが当たり前」の強さ",
          event: `1年後、二人の関係は空気みたいに自然に続いている。周りから見たら派手さはないかもしれない。でも「この人なら絶対に自分を分かってくれる」という確信は、他のどの関係よりも深い。ドラマチックな関係もいいけど、この二人の強さは、そもそも「無理をしない」等身大の愛であることだ。`,
          tone: "synergy",
        },
      ];
  }
}

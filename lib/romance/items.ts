/** 脈あり度を計算する。設問数が0なら0 */
export function romanceScore(yesCount: number, total: number): number {
  return total > 0 ? Math.round((yesCount / total) * 100) : 0;
}

/** 脈あり度（0〜100）から段階の番号（0〜3）を返す */
export function stageIndex(score: number): 0 | 1 | 2 | 3 {
  if (score >= 75) return 3;
  if (score >= 50) return 2;
  if (score >= 25) return 1;
  return 0;
}
